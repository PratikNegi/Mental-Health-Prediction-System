import { useEffect, useState } from "react";
import { Loader2 } from "lucide-react";
import Disclaimer from "./Disclaimer.jsx";

const ARC = "M20 100 A80 80 0 0 1 180 100";

// Scale is 0-10. The fill only shows position on that scale; it never labels a score good or bad.
function Gauge({ value }) {
  const [shown, setShown] = useState(0);
  useEffect(() => {
    const t = setTimeout(() => setShown(value), 80);
    return () => clearTimeout(t);
  }, [value]);
  const v = Math.min(10, Math.max(0, shown));
  return (
    <svg viewBox="0 0 200 118" role="img" aria-label={`Score ${value.toFixed(2)} on a scale from 0 to 10`} className="mx-auto w-full max-w-[280px]">
      <path d={ARC} fill="none" stroke="rgba(255,255,255,.16)" strokeWidth="14" strokeLinecap="round" pathLength="10" />
      <path
        d={ARC} fill="none" stroke="#A8E6DA" strokeWidth="14" strokeLinecap="round" pathLength="10"
        strokeDasharray={`${v} 10`} opacity={v > 0 ? 1 : 0}
        style={{ transition: "stroke-dasharray 1s ease-out" }}
      />
      <text x="20" y="116" textAnchor="middle" fontSize="10" fill="rgba(255,255,255,.7)">0</text>
      <text x="180" y="116" textAnchor="middle" fontSize="10" fill="rgba(255,255,255,.7)">10</text>
    </svg>
  );
}

export default function ResultPanel({ status, score, onReset }) {
  return (
    <section aria-label="Prediction result" aria-live="polite" className="rounded-3xl bg-[#173F3D] p-7 text-white shadow-lg sm:p-9">
      {status === "idle" && (
        <div className="text-center">
          <svg viewBox="0 0 200 118" className="mx-auto w-full max-w-[280px]" aria-hidden="true">
            <path d={ARC} fill="none" stroke="rgba(255,255,255,.16)" strokeWidth="14" strokeLinecap="round" />
          </svg>
          <h2 className="mt-4 font-display text-2xl font-semibold">Your score</h2>
          <p className="mt-2 text-white/75">Fill in the form and submit to get the score.</p>
        </div>
      )}

      {status === "loading" && (
        <div className="py-10 text-center">
          <Loader2 className="mx-auto animate-spin" size={44} aria-hidden="true" />
          <h2 className="mt-5 font-display text-2xl font-semibold">Running your answers through the model…</h2>
          <p className="mt-2 text-white/75">This usually takes a moment.</p>
        </div>
      )}

      {status === "success" && (
        <div className="rise text-center">
          <p className="text-sm font-semibold text-[#A8E6DA]">Model prediction</p>
          <h2 className="mb-2 font-display text-xl font-semibold">Your predicted mental health score</h2>
          <Gauge value={score} />
          <p className="-mt-2 font-display text-7xl font-semibold leading-none">
            {score.toFixed(2)}<span className="ml-1 text-2xl text-white/70">/ 10</span>
          </p>
          <p className="mx-auto mt-5 max-w-xs text-sm leading-relaxed text-white/80">
            Results are generated by a machine-learning model and should not be interpreted as a medical diagnosis.
          </p>
          <button onClick={onReset} className="mt-6 rounded-full bg-white px-7 py-3 font-semibold text-ink transition-colors hover:bg-haze">
            Predict Again
          </button>
        </div>
      )}

      {status !== "success" && <Disclaimer className="mt-6 text-center !text-white/70" />}
    </section>
  );
}
